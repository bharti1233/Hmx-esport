private fun Context.findActivity(): Activity? {
    var current: Context = this
    while (current is ContextWrapper) {
        if (current is Activity) return current
        current = current.baseContext
    }
    return null
}

/**
 * Root HMX theme. Switching [mode] recomposes colour tokens in place: no
 * Activity recreation, navigation reset or form loss. System bar icon contrast
 * is updated in the same frame so switching to Dark never flashes white bars.
 */
@Composable
fun HmxTheme(
    mode: HmxThemeMode,
    onModeChange: (HmxThemeMode) -> Unit = {},
    content: @Composable () -> Unit,
) {
    val systemDark = androidx.compose.foundation.isSystemInDarkTheme()
    val isDark = when (mode) {
        HmxThemeMode.SYSTEM -> systemDark
        HmxThemeMode.LIGHT -> false
        HmxThemeMode.DARK -> true
    }
    val scheme = if (isDark) HmxDarkColorScheme else HmxLightColorScheme
    val state = remember(mode, isDark, onModeChange) {
        HmxThemeState(mode = mode, isDark = isDark, setMode = onModeChange)
    }

    val view = LocalView.current
    if (!view.isInEditMode) {
        SideEffect {
            val activity = view.context.findActivity() ?: return@SideEffect
            val window = activity.window
            WindowCompat.getInsetsController(window, view).apply {
                isAppearanceLightStatusBars = !isDark
                isAppearanceLightNavigationBars = !isDark
            }
            @Suppress("DEPRECATION")
            window.statusBarColor = android.graphics.Color.TRANSPARENT
            @Suppress("DEPRECATION")
            window.navigationBarColor = android.graphics.Color.TRANSPARENT
        }
    }

    CompositionLocalProvider(
        LocalHmxColorScheme provides scheme,
        LocalHmxThemeState provides state,
    ) {
        MaterialTheme(
            colorScheme = scheme.materialColors(),
            typography = HmxTypography,
            shapes = HmxShapesM3,
            content = content,
        )
    }
}

/** Legacy entry point. Prefer [HmxTheme] with a persisted mode. */
@Composable
fun HMXArenaTheme(content: @Composable () -> Unit) {
    HmxTheme(mode = HmxThemeMode.SYSTEM, content = content)
}
