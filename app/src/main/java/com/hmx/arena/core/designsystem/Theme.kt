/** The three user-selectable appearance modes. */
enum class HmxThemeMode {
    SYSTEM,
    LIGHT,
    DARK;

    companion object {
        fun from(raw: String?): HmxThemeMode =
            entries.firstOrNull { it.name == raw } ?: SYSTEM
    }
}

